    function trimZero(text) {
      return text.replace(/\.0+$/, '').replace(/(\.\d*?)0+$/, '$1')
    }

    /** Compact token/request counts: 万/亿 for Chinese, K/M/B otherwise. */
    function formatCompact(value, chinese) {
      const n = Number(value)
      if (!Number.isFinite(n)) return '—'
      if (Math.abs(n) < 1000) return String(Math.round(n))
      if (chinese) {
        if (Math.abs(n) < 1e8) return trimZero((n / 1e4).toFixed(n < 1e6 ? 1 : 0)) + '万'
        return trimZero((n / 1e8).toFixed(2)) + '亿'
      }
      if (Math.abs(n) < 1e6) return trimZero((n / 1e3).toFixed(1)) + 'K'
      if (Math.abs(n) < 1e9) return trimZero((n / 1e6).toFixed(2)) + 'M'
      return trimZero((n / 1e9).toFixed(2)) + 'B'
    }

    function formatExact(value, chinese) {
      const n = Number(value)
      if (!Number.isFinite(n)) return '—'
      return Math.round(n).toLocaleString(chinese ? 'zh-CN' : 'en-US')
    }

    function formatClock(time) {
      const date = new Date(time)
      const pad = (n) => String(n).padStart(2, '0')
      return pad(date.getHours()) + ':' + pad(date.getMinutes()) + ':' + pad(date.getSeconds())
    }

    function monthDay(time) {
      const date = new Date(time)
      const pad = (n) => String(n).padStart(2, '0')
      return pad(date.getMonth() + 1) + '-' + pad(date.getDate())
    }

    function todayKey() {
      const now = new Date()
      const pad = (n) => String(n).padStart(2, '0')
      return now.getFullYear() + '-' + pad(now.getMonth() + 1) + '-' + pad(now.getDate())
    }

    /** Round a peak value up to a readable axis maximum (1/2/5 × 10^n). */
    function niceMax(value) {
      const n = Number(value)
      if (!Number.isFinite(n) || n <= 0) return 1
      const exponent = Math.floor(Math.log10(n))
      const base = Math.pow(10, exponent)
      const ratio = n / base
      const step = ratio <= 1 ? 1 : ratio <= 2 ? 2 : ratio <= 5 ? 5 : 10
      return step * base
    }

    function hourRange(bucket) {
      const from = bucket.key + ':00'
      const next = String((Number(bucket.key) + 1) % 24).padStart(2, '0') + ':00'
      return { from, to: next }
    }

    /**
     * Cached prompt tokens of one aggregated row. The host reports them
     * directly; a host build that omits the field is covered by the observed
     * invariant total = input + cached + output.
     */
    function cacheTokensOf(entry) {
      if (entry && typeof entry.cacheRead === 'number' && Number.isFinite(entry.cacheRead)) {
        return entry.cacheRead
      }
      if (!entry) return 0
      const total = Number(entry.total) || 0
      const input = Number(entry.input) || 0
      const output = Number(entry.output) || 0
      return Math.max(0, total - input - output)
    }

